/*
    CoffeeRuu - Initial SQL Server Database
    Target: SQL Server 2019+ / SQL Server Express
    ORM: Entity Framework Core

    IMPORTANT:
    - This is an initial schema draft based on the CoffeeRuu project scope.
    - Ingredient stock balances must be updated in a SQL transaction by application logic
      when receiving stock or deducting recipe quantities. InventoryTransactions is the audit ledger.
    - Never store plain-text passwords. Store a secure password hash generated by the application.
*/

